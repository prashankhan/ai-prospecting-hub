#!/usr/bin/env node
// Generates src/lib/supabase/database.types.ts from a PostgreSQL database that has the
// migrations applied (local test database or Supabase). Usage:
//   DATABASE_URL=postgres://... node scripts/gen-db-types.mjs
// Output follows the shape expected by @supabase/supabase-js generics.
import { writeFileSync } from "node:fs";
import pg from "pg";

const url = process.env.DATABASE_URL;
if (!url) {
  console.error("DATABASE_URL is required");
  process.exit(1);
}
const client = new pg.Client({ connectionString: url });
await client.connect();

const enums = (await client.query(`
  select t.typname as name, array_agg(e.enumlabel::text order by e.enumsortorder) as values
  from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' group by t.typname order by t.typname`)).rows;
const enumNames = new Set(enums.map((e) => e.name));

const columns = (await client.query(`
  select c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable, c.column_default, c.is_identity,
         c.is_generated, c.ordinal_position
  from information_schema.columns c
  join information_schema.tables t on t.table_name = c.table_name and t.table_schema = c.table_schema
  where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
  order by c.table_name, c.ordinal_position`)).rows;

const fks = (await client.query(`
  select con.conname, cl.relname as table_name, rel.relname as referenced,
    array(select a.attname::text from unnest(con.conkey) k join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k) as cols,
    array(select a.attname::text from unnest(con.confkey) k join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k) as refcols
  from pg_constraint con join pg_class cl on cl.oid = con.conrelid join pg_class rel on rel.oid = con.confrelid
  join pg_namespace n on n.oid = cl.relnamespace
  where con.contype = 'f' and n.nspname = 'public' order by con.conname`)).rows;

const uniques = (await client.query(`
  select cl.relname as table_name,
    array(select a.attname::text from unnest(con.conkey) k join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k) as cols
  from pg_constraint con join pg_class cl on cl.oid = con.conrelid join pg_namespace n on n.oid = cl.relnamespace
  where con.contype in ('u','p') and n.nspname = 'public'`)).rows;

const functions = (await client.query(`
  select p.proname as name, pg_get_function_identity_arguments(p.oid) as args,
    array(select format_type(t, null) from unnest(p.proargtypes) t) as arg_types,
    p.proargnames::text[] as arg_names, format_type(p.prorettype, null) as ret, p.proretset as retset, p.pronargdefaults as ndefaults
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f' and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e') order by p.proname`)).rows;

function scalar(udt, dataType) {
  const t = udt.replace(/^_/, "");
  const isArray = udt.startsWith("_") || dataType === "ARRAY";
  let ts;
  if (enumNames.has(t)) ts = `Database["public"]["Enums"]["${t}"]`;
  else if (["int2", "int4", "int8", "float4", "float8", "numeric"].includes(t)) ts = "number";
  else if (t === "bool") ts = "boolean";
  else if (["json", "jsonb"].includes(t)) ts = "Json";
  else ts = "string";
  return isArray ? `${ts}[]` : ts;
}
function fromFormatType(ft) {
  const isArray = ft.endsWith("[]");
  const base = ft.replace(/\[\]$/, "");
  const map = {
    uuid: "string", text: "string", boolean: "boolean", integer: "number", smallint: "number", bigint: "number",
    jsonb: "Json", json: "Json", "timestamp with time zone": "string", void: "undefined",
  };
  let ts = map[base] ?? (enumNames.has(base) ? `Database["public"]["Enums"]["${base}"]` : null);
  if (!ts && base.startsWith("public.")) ts = enumNames.has(base.slice(7)) ? `Database["public"]["Enums"]["${base.slice(7)}"]` : null;
  if (!ts) ts = base === "jobs" || base === "public.jobs" ? 'Database["public"]["Tables"]["jobs"]["Row"]' : "unknown";
  return isArray ? `${ts}[]` : ts;
}

const tables = {};
for (const c of columns) (tables[c.table_name] ??= []).push(c);

let out = `// Generated by scripts/gen-db-types.mjs — do not edit by hand.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;
for (const [name, cols] of Object.entries(tables)) {
  const row = cols.map((c) => `          ${c.column_name}: ${scalar(c.udt_name, c.data_type)}${c.is_nullable === "YES" ? " | null" : ""};`).join("\n");
  const ins = cols
    .filter((c) => c.is_generated !== "ALWAYS" && !(c.is_identity === "YES"))
    .map((c) => {
      const optional = c.is_nullable === "YES" || c.column_default !== null;
      return `          ${c.column_name}${optional ? "?" : ""}: ${scalar(c.udt_name, c.data_type)}${c.is_nullable === "YES" ? " | null" : ""};`;
    }).join("\n");
  const upd = cols
    .filter((c) => c.is_generated !== "ALWAYS" && !(c.is_identity === "YES"))
    .map((c) => `          ${c.column_name}?: ${scalar(c.udt_name, c.data_type)}${c.is_nullable === "YES" ? " | null" : ""};`).join("\n");
  const rels = fks.filter((f) => f.table_name === name).map((f) => {
    const oneToOne = uniques.some((u) => u.table_name === name && u.cols.length === f.cols.length && u.cols.every((x) => f.cols.includes(x)));
    return `          {
            foreignKeyName: "${f.conname}";
            columns: [${f.cols.map((x) => `"${x}"`).join(", ")}];
            isOneToOne: ${oneToOne};
            referencedRelation: "${f.referenced}";
            referencedColumns: [${f.refcols.map((x) => `"${x}"`).join(", ")}];
          },`;
  }).join("\n");
  out += `      ${name}: {
        Row: {
${row}
        };
        Insert: {
${ins}
        };
        Update: {
${upd}
        };
        Relationships: [
${rels}
        ];
      };
`;
}
out += `    };
    Views: { [_ in never]: never };
    Functions: {
`;
const skip = new Set(["set_updated_at", "handle_new_user", "guard_profile_update", "guard_prospect_update", "forbid_mutation"]);
for (const f of functions) {
  if (skip.has(f.name)) continue;
  const names = f.arg_names ?? [];
  const n = f.arg_types.length;
  const args = f.arg_types.map((t, i) => {
    const optional = i >= n - f.ndefaults;
    return `${names[i] ?? `arg${i}`}${optional ? "?" : ""}: ${fromFormatType(t)}`;
  });
  const ret = fromFormatType(f.ret);
  out += `      ${f.name}: {
        Args: ${args.length ? `{ ${args.join("; ")} }` : "Record<PropertyKey, never>"};
        Returns: ${f.retset ? `${ret}[]` : ret};
      };
`;
}
out += `    };
    Enums: {
${enums.map((e) => `      ${e.name}: ${e.values.map((v) => `"${v}"`).join(" | ")};`).join("\n")}
    };
    CompositeTypes: { [_ in never]: never };
  };
};

type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];
`;
writeFileSync(new URL("../src/lib/supabase/database.types.ts", import.meta.url), out);
await client.end();
console.log(`Wrote types for ${Object.keys(tables).length} tables, ${functions.length} functions, ${enums.length} enums.`);
