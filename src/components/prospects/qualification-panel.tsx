"use client";
import { ExternalLink, RefreshCw, Sparkles } from "lucide-react";
import { QualificationBadge, ScorePill } from "@/components/app/status-badges";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { useAction } from "@/hooks/use-action";
import { formatDateTime } from "@/lib/utils";
import { qualifyNow } from "@/server/actions/outreach";
import type { EvidenceItem, Qualification, SourceRef } from "./types";

export function QualificationPanel({ prospectId, q, status, compact }: { prospectId: string; q: Qualification | null; status: string; compact?: boolean }) {
  const { execute, pending } = useAction(qualifyNow, { success: (d) => `Scored ${d.score} · ${d.status.replace("_", " ")}` });
  if (!q) {
    return (
      <div className="flex flex-col items-start gap-2">
        <p className="text-sm text-muted-foreground">Not assessed yet. The agent researches the business website, then scores fit against this project&apos;s criteria with cited evidence.</p>
        <Button size="sm" variant="primary" loading={pending} onClick={() => execute(prospectId)}><Sparkles /> Research and qualify</Button>
      </div>
    );
  }
  const evidence = (q.evidence as unknown as EvidenceItem[]) ?? [];
  const sources = (q.source_refs as unknown as SourceRef[]) ?? [];
  const missing = (q.missing_information as unknown as string[]) ?? [];
  const source = (ref: string) => sources.find((s) => s.ref.toUpperCase() === ref.toUpperCase());
  return (
    <div className="flex flex-col gap-3">
      <div className="flex flex-wrap items-center gap-3">
        <ScorePill score={q.score} className="text-md" />
        <QualificationBadge status={status} />
        <Badge tone="outline" title="This assessment was generated by AI">AI assessment</Badge>
        <Button size="sm" variant="ghost" className="ml-auto" loading={pending} onClick={() => execute(prospectId)}><RefreshCw /> Re-qualify</Button>
      </div>
      <p className="text-sm leading-relaxed">{q.explanation}</p>
      {evidence.length > 0 && (
        <div>
          <p className="mb-1 text-2xs font-medium tracking-wide text-muted-foreground uppercase">Supporting evidence</p>
          <ul className="flex flex-col gap-1">
            {evidence.map((e, i) => {
              const s = source(e.source_ref);
              return (
                <li key={i} className="flex gap-2 text-sm">
                  <span className="mt-0.5 shrink-0 rounded-sm bg-surface-muted px-1 font-mono text-2xs text-muted-foreground">{e.source_ref}</span>
                  <span>
                    {e.claim}
                    {s?.url && <a href={s.url} target="_blank" rel="noreferrer noopener" className="ml-1 inline-flex items-center text-xs text-accent hover:underline">{s.label}<ExternalLink className="ml-0.5 size-3" /></a>}
                    {s && !s.url && <span className="ml-1 text-xs text-muted-foreground">({s.label})</span>}
                  </span>
                </li>
              );
            })}
          </ul>
        </div>
      )}
      {!compact && missing.length > 0 && (
        <div>
          <p className="mb-1 text-2xs font-medium tracking-wide text-muted-foreground uppercase">Missing information</p>
          <ul className="list-disc pl-5 text-sm text-muted-foreground">{missing.map((m, i) => <li key={i}>{m}</li>)}</ul>
        </div>
      )}
      <p className="text-xs text-subtle-foreground">Researched {formatDateTime(q.researched_at)} · {q.provider} / {q.model}. Score is an internal estimate of fit, not a probability of purchase.</p>
    </div>
  );
}
